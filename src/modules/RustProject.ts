import * as fs from "fs/promises";
import * as path from "path";
import { createHash } from "crypto";

const MARKER = "// Generated by LeetCode Practice for rust-analyzer.\n";
const CARGO_MARKER = "# Generated by LeetCode Practice for rust-analyzer.\n";
export const RUST_PROJECT_DIR = ".leetcode-rust";
export const RUST_PROJECT_LIB = "modules.rs";

export function rustSnippetWithPlaceholders(snippet: string): string {
  // Official templates contain empty function bodies, including constructors.
  return snippet.replace(/(\b(?:pub\s+)?fn\s+\w+\s*\([^{}]*\)[^{}]*\{)\s*\}/g, "$1\n        todo!()\n    }");
}

const LOCAL_BEGIN = "// <leetcode-practice-local>";
const LOCAL_END = "// </leetcode-practice-local>";

/** Remove only our delimited local support before sending Rust to LeetCode. */
export function stripRustLocalSupport(source: string): string {
  const begin = source.indexOf(LOCAL_BEGIN);
  if (begin < 0) return source;
  const end = source.indexOf(LOCAL_END, begin);
  if (end < 0) throw new Error("Incomplete LeetCode local support block; restore its closing marker before submitting.");
  const after = end + LOCAL_END.length;
  return source.slice(0, begin) + source.slice(after).replace(/^\r?\n/, "");
}

export function rustSourceWithLocalSupport(source: string): string {
  const submission = stripRustLocalSupport(source);
  const types = supportTypes(submission);
  if (!types) return submission;
  const newline = submission.endsWith("\n") ? "" : "\n";
  return submission + newline + LOCAL_BEGIN + `
// Generated local support. Excluded from LeetCode Run/Submit.
#[cfg(feature = "leetcode-local")]
mod __leetcode_local {
${types}
}
#[cfg(feature = "leetcode-local")]
use self::__leetcode_local::*;
` + LOCAL_END + "\n";
}

function supportTypes(source: string): string {
  const code = source.replace(/\/\*[\s\S]*?\*\//g, "").replace(/\/\/[^\n]*/g, "");
  const declarations: string[] = [];
  if (/\bimpl\s+Solution\b/.test(code) && !/\b(?:struct|enum|type)\s+Solution\b/.test(code)) {
    declarations.push("pub struct Solution;");
  }
  if (/\bListNode\b/.test(code) && !/\b(?:struct|enum|type)\s+ListNode\b/.test(code)) {
    declarations.push(`#[derive(PartialEq, Eq, Clone, Debug)]
pub struct ListNode { pub val: i32, pub next: Option<Box<ListNode>> }
impl ListNode { pub fn new(val: i32) -> Self { Self { val, next: None } } }`);
  }
  if (/\bTreeNode\b/.test(code) && !/\b(?:struct|enum|type)\s+TreeNode\b/.test(code)) {
    declarations.push(`#[derive(PartialEq, Eq, Debug)]
pub struct TreeNode {
    pub val: i32,
    pub left: Option<std::rc::Rc<std::cell::RefCell<TreeNode>>>,
    pub right: Option<std::rc::Rc<std::cell::RefCell<TreeNode>>>,
}
impl TreeNode { pub fn new(val: i32) -> Self { Self { val, left: None, right: None } } }`);
  }
  return declarations.join("\n");
}

async function writeGenerated(file: string, content: string, marker: string): Promise<void> {
  let previous: string | undefined;
  try { previous = await fs.readFile(file, "utf8"); }
  catch (error) { if ((error as NodeJS.ErrnoException).code !== "ENOENT") throw error; }
  if (previous === content) return;
  if (previous !== undefined && !previous.startsWith(marker)) {
    throw new Error(`Refusing to overwrite non-generated Rust project file: ${file}`);
  }
  await fs.writeFile(file, content, "utf8");
}

/** Ordinary file modules let rust-analyzer locate test runnables in the actual solution. */
export async function syncRustProject(root: string, solutions: readonly string[]): Promise<string> {
  const dir = path.join(root, RUST_PROJECT_DIR);
  const manifest = path.join(root, "Cargo.toml");
  try {
    if (!(await fs.readFile(manifest, "utf8")).startsWith(CARGO_MARKER)) {
      throw new Error("Existing Cargo.toml is user-owned; Rust practice setup will not overwrite it.");
    }
  } catch (error) { if ((error as NodeJS.ErrnoException).code !== "ENOENT") throw error; }
  const modules: string[] = [];
  for (const file of [...new Set(solutions)].sort()) {
    const source = await fs.readFile(file, "utf8");
    const prepared = rustSourceWithLocalSupport(source);
    if (prepared !== source) {
      if (await fs.readFile(file, "utf8") !== source) throw new Error(`Rust solution changed while preparing local support: ${file}`);
      await fs.writeFile(file, prepared, "utf8");
    }
    const relative = path.relative(dir, file).split(path.sep).join("/");
    const id = createHash("sha256").update(relative).digest("hex").slice(0, 16);
    modules.push(`#[path = ${JSON.stringify(relative)}]\nmod problem_${id};`);
  }
  await fs.mkdir(dir, {recursive: true});
  await writeGenerated(manifest, CARGO_MARKER + `[package]
name = "leetcode-practice-solutions"
version = "0.0.0"
edition = "2021"
publish = false

[lib]
path = "${RUST_PROJECT_DIR}/${RUST_PROJECT_LIB}"

[features]
default = ["leetcode-local"]
leetcode-local = []

[workspace]
`, CARGO_MARKER);
  await writeGenerated(path.join(dir, RUST_PROJECT_LIB), MARKER + "#![allow(dead_code, unused_imports, unused_variables)]\n" + modules.join("\n\n") + "\n", MARKER);
  await writeGenerated(path.join(dir, ".gitignore"), CARGO_MARKER + "/target/\n/Cargo.lock\n", CARGO_MARKER);
  // Remove only generated artifacts from earlier Rust workspace layouts.
  for (const [legacy, marker] of [
    [path.join(dir, "lib.rs"), MARKER],
    [path.join(dir, "Cargo.toml"), CARGO_MARKER],
    [path.join(root, ".leetcode-rust-lib.rs"), MARKER],
  ]) {
    try {
      if ((await fs.readFile(legacy, "utf8")).startsWith(marker)) await fs.unlink(legacy);
    } catch (error) { if ((error as NodeJS.ErrnoException).code !== "ENOENT") throw error; }
  }
  return manifest;
}
